"""Produce the per-game analysis the engine's recompiler needs.

Inputs: the original main.dol, decomp-toolkit, optionally a Dolphin symbol map and
hand-written names. Outputs (in games/hmap/analysis/):

  dol_functions.csv   function starts (+ sizes when known)
  symbols.csv         names, including every name in hle_functions.csv
  sdk_report.txt      how each required SDK function was located
and the [sdk] table + game id in games/hmap/game.toml.
"""

from __future__ import annotations

import re
import shutil
import subprocess
from dataclasses import dataclass, field
from pathlib import Path

from . import ppc, project, sdk_finder, symbols, toolchain
from .dol import Dol

REQUIRED_NAMES = ("OSSaveContext", "setjmp")


@dataclass
class AnalysisResult:
    table: symbols.SymbolTable
    sdk: dict[str, int] = field(default_factory=dict)
    missing: list[str] = field(default_factory=list)
    report: list[str] = field(default_factory=list)


def run_dtk(dol_path: Path, work: Path) -> list[symbols.Symbol]:
    dtk = toolchain.require("dtk")
    work.mkdir(parents=True, exist_ok=True)
    shutil.copy2(dol_path, work / "main.dol")
    (work / "config.yml").write_text(
        "# Generated by hmap.py analyze - decomp-toolkit project used only for function boundaries\n"
        "object: main.dol\n"
        "symbols: symbols.txt\n"
        "splits: splits.txt\n",
        encoding="utf-8",
    )
    for stale in ("symbols.txt", "splits.txt"):
        (work / stale).unlink(missing_ok=True)
    print("running decomp-toolkit (dtk dol split) - this analyses the whole DOL and can take a minute")
    subprocess.run([str(dtk), "dol", "split", "config.yml", "out"], cwd=work, check=True)
    text = (work / "symbols.txt").read_text(encoding="utf-8", errors="replace")
    return symbols.parse_dtk_symbols(text)


def bl_target_scan(dol: Dol) -> list[symbols.Symbol]:
    """Fallback function discovery (when decomp-toolkit is unavailable): the entry
    point, every `bl` target, and every prologue (`mflr r0` / `stwu r1,-n(r1)`) that
    follows a `blr`, `rfi` or padding. The engine's recompiler discovers more on its
    own (branch targets, pointers in data, jump tables)."""
    starts = {dol.entry}
    for begin, end in dol.code_ranges():
        previous = 0
        for address in range(begin, end, 4):
            word = dol.word(address)
            if word is None:
                break
            if ppc.is_bl(word):
                target = ppc.branch_target(word, address)
                if dol.is_code(target):
                    starts.add(target)
            prologue = word == ppc.MFLR_R0 or (ppc.opcode(word) == 37 and ppc.rd(word) == 1 and ppc.ra(word) == 1)
            if prologue and previous in (ppc.BLR, ppc.RFI, 0):
                starts.add(address)
            if word != 0 and previous == 0 and address != begin:
                starts.add(address)  # first instruction after padding
            previous = word
    return [symbols.Symbol(a, f"fn_{a:08X}", 0, "function", "scan") for a in sorted(starts)]


def analyse(dol: Dol, dtk_symbols: list[symbols.Symbol], dolphin_map: Path | None, manual: Path,
            hle_names: list[str]) -> AnalysisResult:
    table = symbols.SymbolTable()
    report = []
    table.merge(dtk_symbols, "dtk")
    report.append(f"decomp-toolkit / scan: {sum(1 for s in dtk_symbols if s.kind == 'function')} functions")
    if dolphin_map:
        mapped = symbols.parse_dolphin_map(dolphin_map.read_text(encoding="utf-8", errors="replace"))
        named = [s for s in mapped if not symbols.is_generated_name(s.name)]
        table.merge(mapped, "dolphin")
        report.append(f"Dolphin map {dolphin_map.name}: {len(mapped)} entries, {len(named)} named")

    found = sdk_finder.find_all(dol, sorted(table.functions))
    for name, result in found.items():
        existing = table.address_of(name)
        if result.address is not None:
            if existing is not None and existing != result.address:
                report.append(f"{name}: pattern says {result.address:#010x} but a map says {existing:#010x}; keeping the map")
            else:
                table.add_function(result.address)
                table.add_name(result.address, name, "pattern", override=existing is None)
                report.append(f"{name}: {result.address:#010x} ({result.matches[0].evidence})")
        elif existing is None:
            if result.matches:
                report.append(f"{name}: AMBIGUOUS - {len(result.matches)} candidates:")
                report.extend(f"    {m.address:#010x}  {m.evidence}" for m in result.matches)
            else:
                report.append(f"{name}: no pattern match")
        else:
            report.append(f"{name}: {existing:#010x} (from {table.sources.get(existing)})")

    manual_symbols = symbols.read_csv_names(manual)
    table.merge(manual_symbols, "manual")
    if manual_symbols:
        report.append(f"manual_symbols.csv: {len(manual_symbols)} names")

    needed = list(dict.fromkeys(list(hle_names) + list(REQUIRED_NAMES)))
    missing = [n for n in needed if table.address_of(n) is None]
    sdk = {}
    for key, name in (("os_save_context", "OSSaveContext"), ("setjmp", "setjmp")):
        address = table.address_of(name)
        if address is not None:
            sdk[key] = address
    return AnalysisResult(table, sdk, missing, report)


TOML_ID = re.compile(r'^id\s*=\s*".*"$', re.M)


def write_game_toml(path: Path, game_id: str, sdk: dict[str, int]) -> None:
    text = path.read_text(encoding="utf-8")
    text = TOML_ID.sub(f'id = "{game_id}"', text, count=1)
    for key, value in sdk.items():
        pattern = re.compile(rf"^{key}\s*=.*$", re.M)
        line = f"{key} = 0x{value:08x}"
        text = pattern.sub(line, text, count=1) if pattern.search(text) else text.replace("[sdk]\n", f"[sdk]\n{line}\n", 1)
    path.write_text(text, encoding="utf-8")


def read_sdk(path: Path) -> dict[str, int]:
    import tomllib

    return dict(tomllib.loads(path.read_text(encoding="utf-8")).get("sdk", {}))


def save(result: AnalysisResult, game_id: str) -> None:
    out = project.analysis()
    result.table.write_functions(out / "dol_functions.csv")
    result.table.write_names(out / "symbols.csv")
    (out / "sdk_report.txt").write_text("\n".join(result.report) + "\n", encoding="utf-8")
    write_game_toml(project.REPO_GAME / "game.toml", game_id, result.sdk)
